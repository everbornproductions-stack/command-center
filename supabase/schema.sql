-- Everborn Command: cloud schema (Supabase / Postgres)
-- Run in the Supabase SQL editor. Everything the hosted side needs for a paid product:
-- accounts (Supabase Auth), licences tied to Square subscriptions, paired devices/hubs,
-- the update feed, and optional cross-device sync of projects and subscriptions.
-- Row Level Security: a signed-in user sees only their own rows; service role (webhooks) sees all.

create extension if not exists pgcrypto;

-- ---------- licences ----------
create table if not exists public.licenses (
  id            uuid primary key default gen_random_uuid(),
  key           text unique not null,                  -- what the app stores: EVB-XXXX-XXXX-XXXX
  email         text not null,
  tier          text not null default 'pro' check (tier in ('free','pro','extreme','studio','owner')),
  status        text not null default 'active' check (status in ('active','past_due','cancelled','revoked')),
  source        text not null default 'square' check (source in ('square','manual','promo')),
  square_customer_id     text,
  square_subscription_id text unique,
  max_devices   int not null default 3,
  current_period_end timestamptz,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index if not exists licenses_email_idx on public.licenses (lower(email));

-- ---------- devices / hubs that activated a licence ----------
create table if not exists public.devices (
  id          uuid primary key default gen_random_uuid(),
  license_id  uuid not null references public.licenses(id) on delete cascade,
  device_id   text not null,                            -- random id generated by the app on first run
  name        text,                                     -- "Chris's PC", "Pixel 9"
  platform    text,                                     -- windows | mac | android | ios | web
  app_version text,
  last_seen   timestamptz not null default now(),
  created_at  timestamptz not null default now(),
  unique (license_id, device_id)
);

-- ---------- update feed (what the app polls) ----------
create table if not exists public.releases (
  id          uuid primary key default gen_random_uuid(),
  channel     text not null default 'stable',
  version     text not null,
  notes       text,
  url         text,
  minimum     text,
  published   boolean not null default false,
  created_at  timestamptz not null default now()
);

-- ---------- optional sync (phone <-> desktop), owned by the signed-in user ----------
create table if not exists public.user_sync (
  user_id     uuid not null references auth.users(id) on delete cascade,
  kind        text not null check (kind in ('projects','subscriptions','settings','skills')),
  data        jsonb not null default '{}'::jsonb,
  updated_at  timestamptz not null default now(),
  primary key (user_id, kind)
);

-- ---------- promo codes (owner, friends, launch deals) ----------
create table if not exists public.promo_codes (
  code        text primary key,
  tier        text not null default 'pro',
  max_uses    int not null default 1,
  uses        int not null default 0,
  expires_at  timestamptz,
  created_at  timestamptz not null default now()
);

-- ---------- audit of webhook events (idempotency) ----------
create table if not exists public.square_events (
  event_id    text primary key,
  type        text,
  received_at timestamptz not null default now(),
  payload     jsonb
);

-- ---------- helpers ----------
create or replace function public.touch_updated_at() returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end $$;
drop trigger if exists licenses_touch on public.licenses;
create trigger licenses_touch before update on public.licenses for each row execute function public.touch_updated_at();

-- Generate a licence key like EVB-7K2M-9QHD-4XTP (no 0/O/1/I)
create or replace function public.gen_license_key() returns text language plpgsql as $$
declare alphabet text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789'; res text := 'EVB'; i int; j int;
begin
  for i in 1..3 loop
    res := res || '-';
    for j in 1..4 loop res := res || substr(alphabet, 1 + floor(random() * length(alphabet))::int, 1); end loop;
  end loop;
  return res;
end $$;

-- The app calls this (anon key is enough): returns tier/status for a key and registers the device.
create or replace function public.verify_license(p_key text, p_device_id text, p_name text default null, p_platform text default null, p_version text default null)
returns table (ok boolean, tier text, status text, email text, period_end timestamptz, devices int, max_devices int, message text)
language plpgsql security definer set search_path = public as $$
declare l public.licenses%rowtype; n int;
begin
  select * into l from public.licenses where key = upper(trim(p_key));
  if not found then return query select false, 'free', 'unknown', null::text, null::timestamptz, 0, 0, 'Licence key not found'; return; end if;
  insert into public.devices (license_id, device_id, name, platform, app_version)
    values (l.id, p_device_id, p_name, p_platform, p_version)
    on conflict (license_id, device_id) do update set last_seen = now(), name = coalesce(excluded.name, devices.name), app_version = coalesce(excluded.app_version, devices.app_version);
  select count(*) into n from public.devices d where d.license_id = l.id and d.last_seen > now() - interval '30 days';
  if l.status <> 'active' then return query select false, 'free', l.status, l.email, l.current_period_end, n, l.max_devices, 'Licence is ' || l.status; return; end if;
  if n > l.max_devices then return query select false, 'free', 'device_limit', l.email, l.current_period_end, n, l.max_devices, 'Too many devices on this licence'; return; end if;
  return query select true, l.tier, l.status, l.email, l.current_period_end, n, l.max_devices, 'ok';
end $$;

-- Redeem a promo code → creates a licence and returns the key.
create or replace function public.redeem_promo(p_code text, p_email text)
returns table (key text, tier text, message text) language plpgsql security definer set search_path = public as $$
declare pc public.promo_codes%rowtype; k text;
begin
  select * into pc from public.promo_codes where code = upper(trim(p_code)) for update;
  if not found or pc.uses >= pc.max_uses or (pc.expires_at is not null and pc.expires_at < now()) then
    return query select null::text, null::text, 'Code is invalid, used up, or expired'; return;
  end if;
  k := public.gen_license_key();
  insert into public.licenses (key, email, tier, status, source) values (k, lower(trim(p_email)), pc.tier, 'active', 'promo');
  update public.promo_codes set uses = uses + 1 where code = pc.code;
  return query select k, pc.tier, 'ok';
end $$;

-- ---------- RLS ----------
alter table public.licenses enable row level security;
alter table public.devices enable row level security;
alter table public.releases enable row level security;
alter table public.user_sync enable row level security;
alter table public.promo_codes enable row level security;
alter table public.square_events enable row level security;

-- licences: a signed-in user can read licences on their own email; nobody can write except service role
drop policy if exists "own licence by email" on public.licenses;
create policy "own licence by email" on public.licenses for select to authenticated using (lower(email) = lower(auth.jwt() ->> 'email'));
-- releases: anyone can read published releases (the update feed)
drop policy if exists "published releases" on public.releases;
create policy "published releases" on public.releases for select to anon, authenticated using (published);
-- user_sync: owner only
drop policy if exists "own sync" on public.user_sync;
create policy "own sync" on public.user_sync for all to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());

grant execute on function public.verify_license(text, text, text, text, text) to anon, authenticated;
grant execute on function public.redeem_promo(text, text) to anon, authenticated;

